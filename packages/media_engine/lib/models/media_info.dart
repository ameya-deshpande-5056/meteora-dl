import 'package:meta/meta.dart';
import 'format_info.dart';
import 'stream_type.dart';

@immutable
class SubtitleTrackInfo {
  final String code;
  final String name;
  final bool isAutoGenerated;

  const SubtitleTrackInfo({
    required this.code,
    required this.name,
    this.isAutoGenerated = false,
  });

  String get displayLabel {
    final cleanName = name.isNotEmpty ? name : code;
    final label = cleanName.toLowerCase() == code.toLowerCase()
        ? code
        : '$cleanName ($code)';
    return isAutoGenerated ? '$label • Auto' : label;
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is SubtitleTrackInfo &&
          runtimeType == other.runtimeType &&
          code == other.code &&
          isAutoGenerated == other.isAutoGenerated;

  @override
  int get hashCode => Object.hash(code, isAutoGenerated);
}

@immutable
class MediaInfo {
  final String id;
  final String title;
  final String? uploader;
  final String? uploaderId;
  final int? durationSeconds;
  final String? thumbnail;
  final String? webpageUrl;
  final String? extractor;
  final String? description;
  final List<FormatInfo> formats;
  final List<String> subtitles;
  final List<String> automaticCaptions;
  final List<SubtitleTrackInfo> subtitleTracks;

  const MediaInfo({
    required this.id,
    required this.title,
    this.uploader,
    this.uploaderId,
    this.durationSeconds,
    this.thumbnail,
    this.webpageUrl,
    this.extractor,
    this.description,
    required this.formats,
    this.subtitles = const [],
    this.automaticCaptions = const [],
    this.subtitleTracks = const [],
  });

  bool get hasCreatorSubtitles => subtitles.isNotEmpty;
  bool get hasAnySubtitles =>
      subtitles.isNotEmpty || automaticCaptions.isNotEmpty || subtitleTracks.isNotEmpty;

  List<FormatInfo> get videoOnlyFormats =>
      formats.where((f) => f.streamType == StreamType.videoOnly).toList();

  List<FormatInfo> get audioOnlyFormats =>
      formats.where((f) => f.streamType == StreamType.audioOnly).toList();

  List<FormatInfo> get combinedFormats =>
      formats.where((f) => f.streamType == StreamType.combined).toList();

  /// Video streams sorted highest resolution -> fps -> video-only preference -> bitrate.
  List<FormatInfo> get selectableVideoFormats {
    final list = formats.where((f) => f.streamType.hasVideo).toList();
    list.sort((a, b) {
      final hCmp = (b.height ?? 0).compareTo(a.height ?? 0);
      if (hCmp != 0) return hCmp;
      final fpsCmp = (b.fps ?? 0).compareTo(a.fps ?? 0);
      if (fpsCmp != 0) return fpsCmp;
      final splitCmp = (a.streamType == StreamType.videoOnly ? 0 : 1)
          .compareTo(b.streamType == StreamType.videoOnly ? 0 : 1);
      if (splitCmp != 0) return splitCmp;
      return (b.vbr ?? b.tbr ?? 0).compareTo(a.vbr ?? a.tbr ?? 0);
    });
    return list;
  }

  /// Audio streams sorted highest bitrate -> codec clarity -> audio-only first.
  List<FormatInfo> get selectableAudioFormats {
    final audioOnly = audioOnlyFormats.toList();
    audioOnly.sort((a, b) {
      final bBitrate = b.abr ?? b.tbr ?? 0;
      final aBitrate = a.abr ?? a.tbr ?? 0;
      final bitCmp = bBitrate.compareTo(aBitrate);
      if (bitCmp != 0) return bitCmp;
      return (b.estimatedSizeBytes ?? 0).compareTo(a.estimatedSizeBytes ?? 0);
    });
    if (audioOnly.isNotEmpty) return audioOnly;

    final combined = combinedFormats.toList();
    combined.sort((a, b) => (b.abr ?? b.tbr ?? 0).compareTo(a.abr ?? a.tbr ?? 0));
    return combined;
  }

  /// All usable subtitle tracks (creator tracks first, then auto-generated captions, excluding live_chat).
  List<SubtitleTrackInfo> get availableSubtitleTracks {
    if (subtitleTracks.isNotEmpty) {
      return subtitleTracks.where((t) => t.code != 'live_chat').toList();
    }
    return [
      for (final code in subtitles)
        if (code != 'live_chat') SubtitleTrackInfo(code: code, name: code),
      for (final code in automaticCaptions)
        if (code != 'live_chat' && !subtitles.contains(code))
          SubtitleTrackInfo(code: code, name: code, isAutoGenerated: true),
    ];
  }

  factory MediaInfo.fromJson(Map<String, dynamic> json) {
    final rawFormats = json['formats'] as List<dynamic>? ?? [];
    final parsedFormats = rawFormats
        .whereType<Map<String, dynamic>>()
        .where((f) {
          final ext = (f['ext'] ?? '').toString().toLowerCase();
          final vcodec = f['vcodec']?.toString();
          final acodec = f['acodec']?.toString();
          final note = (f['format_note'] ?? '').toString().toLowerCase();
          if (ext == 'mhtml' || note.contains('storyboard')) return false;
          if (vcodec == 'none' && acodec == 'none') return false;
          return true;
        })
        .map((f) => FormatInfo.fromJson(f))
        .toList();

    final rawSubtitles = json['subtitles'] as Map? ?? const {};
    final rawAutoCaptions = json['automatic_captions'] as Map? ?? const {};
    final videoLang = json['language']?.toString();

    final tracks = <SubtitleTrackInfo>[];
    for (final entry in rawSubtitles.entries) {
      final code = entry.key.toString();
      if (code == 'live_chat') continue;
      tracks.add(SubtitleTrackInfo(
        code: code,
        name: _extractTrackName(entry.value, code),
        isAutoGenerated: false,
      ));
    }

    // Put primary auto-captions (video original language / English) near top of auto-captions
    final autoEntries = rawAutoCaptions.entries.toList()
      ..sort((a, b) {
        final aCode = a.key.toString();
        final bCode = b.key.toString();
        final aPriority = _autoCaptionPriority(aCode, videoLang);
        final bPriority = _autoCaptionPriority(bCode, videoLang);
        if (aPriority != bPriority) return aPriority.compareTo(bPriority);
        return aCode.compareTo(bCode);
      });

    for (final entry in autoEntries) {
      final code = entry.key.toString();
      if (code == 'live_chat') continue;
      if (tracks.any((t) => t.code == code && !t.isAutoGenerated)) continue;
      tracks.add(SubtitleTrackInfo(
        code: code,
        name: _extractTrackName(entry.value, code),
        isAutoGenerated: true,
      ));
    }

    return MediaInfo(
      id: (json['id'] ?? '').toString(),
      title: (json['title'] ?? 'Untitled Media').toString(),
      uploader: json['uploader'] as String?,
      uploaderId: json['uploader_id'] as String?,
      durationSeconds: json['duration'] is num ? (json['duration'] as num).toInt() : null,
      thumbnail: json['thumbnail'] as String?,
      webpageUrl: json['webpage_url'] as String?,
      extractor: json['extractor_key'] as String? ?? json['extractor'] as String?,
      description: json['description'] as String?,
      formats: parsedFormats,
      subtitles: rawSubtitles.keys.map((k) => k.toString()).toList(),
      automaticCaptions: rawAutoCaptions.keys.map((k) => k.toString()).toList(),
      subtitleTracks: tracks,
    );
  }

  static int _autoCaptionPriority(String code, String? videoLang) {
    if (code.endsWith('-orig')) return 0;
    if (videoLang != null && code.startsWith(videoLang)) return 1;
    if (code == 'en' || code.startsWith('en-')) return 2;
    return 3;
  }

  static String _extractTrackName(dynamic value, String fallbackCode) {
    if (value is List && value.isNotEmpty) {
      final first = value.first;
      if (first is Map && first['name'] != null) {
        final name = first['name'].toString().trim();
        if (name.isNotEmpty) return name;
      }
    }
    return fallbackCode;
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'uploader': uploader,
    'uploader_id': uploaderId,
    'duration': durationSeconds,
    'thumbnail': thumbnail,
    'webpage_url': webpageUrl,
    'extractor': extractor,
    'description': description,
    'formats': formats.map((f) => f.toJson()).toList(),
    'subtitles': subtitles,
    'automatic_captions': automaticCaptions,
  };
}
