import 'package:media_engine/media_engine.dart';
import 'package:test/test.dart';

void main() {
  group('MediaInfo formats & subtitles parsing', () {
    test('filters storyboards and sorts selectable video/audio formats and subtitle tracks', () {
      final media = MediaInfo.fromJson({
        'id': 'abc123',
        'title': 'Test Video',
        'language': 'en',
        'formats': [
          {
            'format_id': 'sb0',
            'format_note': 'storyboard',
            'ext': 'mhtml',
            'vcodec': 'none',
            'acodec': 'none',
          },
          {
            'format_id': '18',
            'format_note': '360p',
            'ext': 'mp4',
            'height': 360,
            'fps': 30,
            'vcodec': 'avc1.42001E',
            'acodec': 'mp4a.40.2',
            'abr': 96,
            'filesize': 15 * 1024 * 1024,
          },
          {
            'format_id': '248',
            'format_note': '1080p',
            'ext': 'webm',
            'height': 1080,
            'fps': 60,
            'vcodec': 'vp09.00.40.08',
            'acodec': 'none',
            'vbr': 2800,
            'filesize': 55 * 1024 * 1024,
          },
          {
            'format_id': '140',
            'format_note': 'medium',
            'ext': 'm4a',
            'vcodec': 'none',
            'acodec': 'mp4a.40.2',
            'abr': 128,
            'filesize': 4 * 1024 * 1024,
          },
          {
            'format_id': '251',
            'format_note': 'high',
            'ext': 'webm',
            'vcodec': 'none',
            'acodec': 'opus',
            'abr': 160,
            'filesize': 5 * 1024 * 1024,
          },
        ],
        'subtitles': {
          'en': [
            {'ext': 'vtt', 'name': 'English'},
          ],
          'ja': [
            {'ext': 'srt', 'name': 'Japanese'},
          ],
        },
        'automatic_captions': {
          'es': [
            {'ext': 'vtt', 'name': 'Spanish'},
          ],
        },
      });

      expect(media.formats.any((f) => f.formatId == 'sb0'), isFalse);
      expect(media.selectableVideoFormats.first.formatId, equals('248'));
      expect(media.selectableVideoFormats.first.displayVideoCodec, equals('VP9'));
      expect(
        media.selectableVideoFormats.first.videoSelectionLabel,
        equals('1080p60 • VP9 • WEBM (55.0 MB)'),
      );
      expect(media.selectableAudioFormats.first.formatId, equals('251'));
      expect(media.selectableAudioFormats.first.displayAudioCodec, equals('Opus'));
      expect(
        media.selectableAudioFormats.first.audioSelectionLabel,
        equals('160 kbps • Opus • WEBM (5.0 MB)'),
      );

      final tracks = media.availableSubtitleTracks;
      expect(tracks.length, equals(3));
      expect(tracks[0].code, equals('en'));
      expect(tracks[0].isAutoGenerated, isFalse);
      expect(tracks[0].displayLabel, equals('English (en)'));
      expect(tracks[2].code, equals('es'));
      expect(tracks[2].isAutoGenerated, isTrue);
      expect(tracks[2].displayLabel, equals('Spanish (es) • Auto'));
    });

    test('reports hasCreatorSubtitles false when only automatic_captions exist', () {
      final media = MediaInfo.fromJson({
        'id': 'abc123',
        'title': 'Auto Captions Only',
        'formats': [],
        'subtitles': {},
        'automatic_captions': {
          'es': [
            {'ext': 'vtt', 'name': 'Spanish'},
          ],
        },
      });

      expect(media.hasCreatorSubtitles, isFalse);
      expect(media.hasAnySubtitles, isTrue);
      expect(media.availableSubtitleTracks.single.isAutoGenerated, isTrue);
    });
  });

  group('SimpleDownloadCommandBuilder', () {
    const url = 'https://www.youtube.com/watch?v=dQw4w9WgXcQ';

    const video1080Av1 = FormatInfo(
      formatId: '399',
      formatNote: '1080p60',
      ext: 'mp4',
      height: 1080,
      fps: 60,
      vcodec: 'av01.0.08M.08',
      filesize: 40 * 1024 * 1024,
      streamType: StreamType.videoOnly,
    );
    const audio160Opus = FormatInfo(
      formatId: '251',
      formatNote: 'high',
      ext: 'webm',
      acodec: 'opus',
      abr: 160,
      filesize: 5 * 1024 * 1024,
      streamType: StreamType.audioOnly,
    );
    const subEn = SubtitleTrackInfo(code: 'en', name: 'English');
    const subEsAuto = SubtitleTrackInfo(code: 'es', name: 'Spanish', isAutoGenerated: true);

    const mediaWithSubs = MediaInfo(
      id: 'v1',
      title: 'With Subtitles',
      formats: [video1080Av1, audio160Opus],
      subtitles: ['en'],
      automaticCaptions: ['es'],
      subtitleTracks: [subEn, subEsAuto],
    );

    const mediaWithoutSubs = MediaInfo(
      id: 'v2',
      title: 'No Subtitles',
      formats: [
        FormatInfo(
          formatId: '18',
          formatNote: '360p',
          ext: 'mp4',
          height: 360,
          vcodec: 'avc1',
          acodec: 'mp4a',
          streamType: StreamType.combined,
        ),
      ],
    );

    test('uses selected video+audio format IDs and chosen subtitle languages', () {
      final cmd = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.videoAudioSubtitles,
        media: mediaWithSubs,
        selectedVideo: video1080Av1,
        selectedAudio: audio160Opus,
        selectedSubtitles: const [subEn, subEsAuto],
      );

      expect(cmd, containsAllInOrder(['-f', '399+251']));
      expect(cmd, contains('--write-subs'));
      expect(cmd, contains('--write-auto-subs'));
      expect(cmd, contains('--embed-subs'));
      expect(cmd, containsAllInOrder(['--sub-langs', 'en,es']));
      expect(cmd, containsAllInOrder(['--sleep-subtitles', '2']));
      expect(cmd.last, equals(url));
    });

    test('omits subtitle flags when user selects no subtitles on extracted media', () {
      final cmd = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.videoAudioSubtitles,
        media: mediaWithoutSubs,
        selectedVideo: mediaWithoutSubs.formats.first,
      );

      expect(cmd, containsAllInOrder(['-f', '18']));
      expect(cmd, isNot(contains('--write-subs')));
      expect(cmd, isNot(contains('--embed-subs')));
    });

    test('videoOnly uses explicit video format or bestvideo fallback', () {
      final explicitCmd = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.videoOnly,
        media: mediaWithSubs,
        selectedVideo: video1080Av1,
      );
      expect(explicitCmd, containsAllInOrder(['-f', '399']));
      expect(explicitCmd, isNot(contains('-x')));

      final combinedFallback = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.videoOnly,
        media: mediaWithoutSubs,
      );
      expect(combinedFallback, containsAllInOrder(['-f', 'bestvideo/best']));
    });

    test('audioOnly uses explicit audio format ID and extract flag', () {
      final cmd = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.audioOnly,
        media: mediaWithSubs,
        selectedAudio: audio160Opus,
      );

      expect(cmd, containsAllInOrder(['-f', '251', '-x']));
      expect(cmd.last, equals(url));
    });

    test('subtitlesOnly skips media download and uses selected subtitle tracks', () {
      final cmd = SimpleDownloadCommandBuilder.buildCommand(
        url: url,
        mode: DownloadMode.subtitlesOnly,
        media: mediaWithSubs,
        selectedSubtitles: const [subEsAuto],
      );
      expect(cmd, contains('--skip-download'));
      expect(cmd, contains('--write-auto-subs'));
      expect(cmd, isNot(contains('--write-subs')));
      expect(cmd, containsAllInOrder(['--sub-langs', 'es']));
      expect(cmd, containsAllInOrder(['--sub-format', 'srt/vtt/best']));
    });
  });
}
